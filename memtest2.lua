local Memory = dofile("/home/vm/mem.lua")
local m = Memory.new(0x10000000)
m:w32(0, 0xDEADBEEF)
m:w32(0x80000000, 0x12345678)
m:w8(0x80000004, 0xAB)
print(string.format("low  = %08X (want DEADBEEF)", m:r32(0)))
print(string.format("high = %08X (want 12345678)", m:r32(0x80000000)))
print(string.format("byte = %02X (want AB)", m:r8(0x80000004)))
print(string.format("empty= %08X (want 0)", m:r32(0x40000000)))
